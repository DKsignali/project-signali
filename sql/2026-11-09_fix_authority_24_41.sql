-- Писмата по тези сигнали са изпратени отдавна - тази промяна засяга САМО
-- какво показва картата, не променя нищо в маршрутизацията на нови сигнали.
--
-- №24 (ул. Рая, 20.08.2026): подаден 53 минути преди да заработи определянето
--     на района по координати. Тогава районът идваше само от предположението
--     на ИИ, той не върна район и преписката отиде централно.
--     Маркерът 42.1346071, 24.7076024 е в Район Западен.
--
-- №41 (ул. Академик Петър Динеков, кв. Христо Ботев, 12.10.2026): кварталът
--     „Христо Ботев" беше разчитан като бул. „Христо Ботев", затова сигналът
--     мина за главен булевард и отиде централно. Маркерът 42.13108, 24.73437
--     е в Район Южен.
--
-- Първо погледни какво ще бъде променено:
--   SELECT id, location, latitude, longitude, responsible_authority
--   FROM public.signals WHERE id IN (24, 41);
-- =============================================================================

UPDATE public.signals
SET    responsible_authority = 'Район Западен'
WHERE  id = 24
  AND  responsible_authority = 'Община Пловдив';

UPDATE public.signals
SET    responsible_authority = 'Район Южен'
WHERE  id = 41
  AND  responsible_authority = 'Община Пловдив';

